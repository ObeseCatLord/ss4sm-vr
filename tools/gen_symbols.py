#!/usr/bin/env python3
"""Generate src/se4/symbols_gen.hpp: per-build RVAs for the names listed in tools/symbols.txt.

Every RVA comes from docs/re/builds/<exe>.json (registration-table harvest) or from
docs/re/builds/manual.json (addresses established by gate notes, keyed by exe and name).
A name missing from any build is emitted as 0 for that build and must be handled as unavailable.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
BUILDS = ['Sam4', 'Sam4_Unrestricted', 'SamSM', 'SamSM_Unrestricted']


def main():
    wanted = [l.split('#')[0].strip() for l in (ROOT / 'tools/symbols.txt').read_text().splitlines()]
    wanted = [w for w in wanted if w]
    fps = {f['file'][:-4]: f for f in json.load(open(ROOT / 'docs/re/builds/fingerprints.json'))}
    manual = json.load(open(ROOT / 'docs/re/builds/manual.json'))
    members = json.load(open(ROOT / 'docs/re/builds/members.json'))
    mwanted = [l.split('#')[0].strip() for l in (ROOT / 'tools/members.txt').read_text().splitlines()]
    mwanted = [w for w in mwanted if w]
    rows = []
    for b in BUILDS:
        h = json.load(open(ROOT / f'docs/re/builds/{b}.json'))
        base = 0x140000000
        vals = []
        for w in wanted:
            kind, name = w.split(':', 1)
            if kind == 'manual':
                va = manual.get(b, {}).get(name)
                va = int(va, 16) if va else 0
            else:
                rec = h['variables' if kind == 'var' else 'functions'].get(name)
                va = int(rec['va'], 16) if rec else 0
            vals.append(va - base if va else 0)
        mvals = [int(members.get(b, {}).get(w, '0'), 16) for w in mwanted]
        rows.append((b, fps[b], vals, mvals))
    ident = [w.split(':', 1)[1].replace('::', '_') for w in wanted]
    out = ['// Generated by tools/gen_symbols.py from docs/re/builds. Do not edit.', '#pragma once',
           '#include <cstdint>', 'namespace se4::gen {', 'enum Sym : unsigned {']
    mident = [w.replace('::', '_') for w in mwanted]
    out += ['  %s,' % i for i in ident] + ['  SymCount', '};', 'enum Mem : unsigned {']
    out += ['  %s,' % i for i in mident] + ['  MemCount', '};',
            'struct BuildTable { const char* name; uint32_t timeDateStamp; uint32_t sizeOfImage; uint32_t build; '
            'uint32_t textCrc32; uint32_t rva[SymCount]; uint32_t mem[MemCount]; };',
            'inline constexpr BuildTable kBuilds[] = {']
    for b, fp, vals, mvals in rows:
        out.append('  {"%s", 0x%08x, 0x%08x, %d, 0x%08x, {%s}, {%s}},' % (
            b, fp['time_date_stamp'], fp['size_of_image'], fp['build'], fp['text_crc32'],
            ', '.join('0x%x' % v for v in vals), ', '.join('0x%x' % v for v in mvals)))
    out += ['};', 'inline constexpr const char* kSymNames[] = {'] + ['  "%s",' % w for w in wanted] + ['};', '}']
    (ROOT / 'src/se4/symbols_gen.hpp').write_text('\n'.join(out) + '\n')
    missing = [(b, w) for b, _, vals, _ in rows for w, v in zip(wanted, vals) if not v]
    missing += [(b, 'member:' + w) for b, _, _, mvals in rows for w, v in zip(mwanted, mvals) if not v]
    for b, w in missing:
        print('missing', b, w, file=sys.stderr)


if __name__ == '__main__':
    main()
